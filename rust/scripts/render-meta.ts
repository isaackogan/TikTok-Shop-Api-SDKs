import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

interface Operation {
  operationId: string;
  tag: string;
  group: string;
  method: string;
  path: string;
  requiresShopCipher: boolean;
}
interface Webhook {
  type: number;
  schema: string;
  eventType?: string;
}
interface Meta {
  operations: Operation[];
  webhooks: Webhook[];
}

export interface GeneratedFn {
  /** Module under `apis`, e.g. `orders_api`. */
  module: string;
  name: string;
  doc: string[];
  /** `[name, type]` for every parameter after `configuration`. */
  params: [string, string][];
  /** The success type, e.g. `models::GetOrderListResponse`. */
  ret: string;
}

/** Split on commas that are not inside `<>`, `()` or `[]`. */
export function splitTopLevel(s: string): string[] {
  const parts: string[] = [];
  let depth = 0;
  let cur = '';
  for (const ch of s) {
    if ('<([' .includes(ch)) depth++;
    else if ('>)]'.includes(ch)) depth--;
    if (ch === ',' && depth === 0) {
      parts.push(cur.trim());
      cur = '';
    } else cur += ch;
  }
  if (cur.trim()) parts.push(cur.trim());
  return parts;
}

const FN_RE = /^((?:\/\/\/.*\n)*)pub async fn (\w+)\(configuration: &configuration::Configuration((?:, .*?)?)\) -> Result<(.+?), Error<\w+>> \{$/gm;

/** Every `pub async fn` of a generated `*_api.rs` file. */
export function findFns(module: string, src: string): GeneratedFn[] {
  const fns: GeneratedFn[] = [];
  for (const m of src.matchAll(FN_RE)) {
    const params = splitTopLevel(m[3].replace(/^, /, '')).map((p): [string, string] => {
      const i = p.indexOf(':');
      return [p.slice(0, i).trim(), p.slice(i + 1).trim()];
    });
    const doc = m[1].split('\n').filter(Boolean).map((l) => l.replace(/^\/\/\/ ?/, ''));
    fns.push({ module, name: m[2], doc, params, ret: m[4] });
  }
  return fns;
}

/** camelCase group name to snake_case, keeping "TikTok" one word (ruling R9). */
export function snake(group: string): string {
  return group
    .replace(/TikTok/g, 'Tiktok')
    .replace(/([A-Z])/g, '_$1')
    .toLowerCase();
}

/** `fulfilledByTikTok` to `FulfilledByTikTok`. */
export const pascal = (group: string) => group[0].toUpperCase() + group.slice(1);

const q = (s: string) => JSON.stringify(s);

/** Write `<dir>/meta.rs` and `<dir>/groups.rs` from `meta.json` and the generated `apis/*_api.rs` files. */
export function renderMeta(metaPath: string, dir: string): void {
  const meta = JSON.parse(readFileSync(metaPath, 'utf8')) as Meta;
  const fns: GeneratedFn[] = [];
  for (const f of readdirSync(join(dir, 'apis')).filter((n) => n.endsWith('_api.rs'))) {
    fns.push(...findFns(f.replace(/\.rs$/, ''), readFileSync(join(dir, 'apis', f), 'utf8')));
  }

  const groups = new Map<string, { tag: string; module: string; ops: { op: Operation; fn: GeneratedFn }[] }>();
  const rows: string[] = [];
  for (const op of meta.operations) {
    const want = op.operationId.toLowerCase();
    const hits = fns.filter((f) => f.name.replace(/_/g, '') === want);
    if (hits.length !== 1) {
      throw new Error(`operation ${op.operationId}: expected exactly one generated function, found ${hits.map((h) => `${h.module}::${h.name}`).join(', ') || 'none'}`);
    }
    const [fn] = hits;
    const g = groups.get(op.group) ?? { tag: op.tag, module: fn.module, ops: [] };
    if (g.module !== fn.module) throw new Error(`group ${op.group} spans modules ${g.module} and ${fn.module}`);
    g.ops.push({ op, fn });
    groups.set(op.group, g);
    rows.push(
      `    OperationMeta { operation_id: ${q(op.operationId)}, tag: ${q(op.tag)}, group: ${q(snake(op.group))}, method: ${q(fn.name)}, http_method: ${q(op.method.toUpperCase())}, path: ${q(op.path)}, requires_shop_cipher: ${op.requiresShopCipher} },`,
    );
  }
  const sortedGroups = [...groups.entries()].sort(([a], [b]) => a.localeCompare(b));
  const groupRows = sortedGroups.map(
    ([g, v]) => `    GroupMeta { name: ${q(snake(g))}, tag: ${q(v.tag)}, type_name: ${q(pascal(g) + 'Api')} },`,
  );
  const webhookRows = meta.webhooks.map(
    (w) => `    WebhookMeta { webhook_type: ${w.type}, schema: ${q(w.schema)}, event_type: ${w.eventType ? `Some(${q(w.eventType)})` : 'None'} },`,
  );
  const eventTypes = meta.webhooks
    .filter((w) => w.eventType)
    .sort((a, b) => a.type - b.type)
    .map((w) => `    (${w.type}, ${q(w.eventType!)}),`);

  writeFileSync(
    join(dir, 'meta.rs'),
    `// Code generated by scripts/render-meta.ts from the OpenAPI spec. DO NOT EDIT.

/// One API operation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OperationMeta {
    pub operation_id: &'static str,
    pub tag: &'static str,
    /// The snake_case group name, e.g. \`fulfilled_by_tiktok\`.
    pub group: &'static str,
    /// The method on the group, e.g. \`get_order_list\`.
    pub method: &'static str,
    /// Upper case.
    pub http_method: &'static str,
    pub path: &'static str,
    pub requires_shop_cipher: bool,
}

/// One API group.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct GroupMeta {
    /// The snake_case field name on the client.
    pub name: &'static str,
    pub tag: &'static str,
    /// The group's struct in \`crate::generated::groups\`.
    pub type_name: &'static str,
}

/// One webhook type.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct WebhookMeta {
    pub webhook_type: i64,
    pub schema: &'static str,
    pub event_type: Option<&'static str>,
}

/// Every API operation.
pub const OPERATIONS: &[OperationMeta] = &[
${rows.join('\n')}
];

/// Every API group.
pub const GROUPS: &[GroupMeta] = &[
${groupRows.join('\n')}
];

/// Every webhook type.
pub const WEBHOOKS: &[WebhookMeta] = &[
${webhookRows.join('\n')}
];

/// Webhook type to event name.
pub const EVENT_TYPES: &[(i64, &str)] = &[
${eventTypes.join('\n')}
];
`,
  );

  const structs = sortedGroups.map(([g, v]) => {
    const T = pascal(g) + 'Api';
    const methods = v.ops
      .map(({ fn }) => {
        const sig = fn.params.map(([n, t]) => `, ${n}: ${t}`).join('');
        const args = fn.params.map(([n]) => `, ${n}`).join('');
        const doc = fn.doc.map((l) => `    /// ${l}`.trimEnd()).join('\n');
        return `${doc ? doc + '\n' : ''}    pub async fn ${fn.name}(&self${sig}) -> Result<${fn.ret}, Error> {
        apis::${v.module}::${fn.name}(&self.config${args}).await.map_err(Error::from)
    }`;
      })
      .join('\n\n');
    return `/// The \`${v.tag}\` operations.
#[derive(Clone)]
pub struct ${T} {
    config: Arc<Configuration>,
}

impl ${T} {
    pub(crate) fn new(config: Arc<Configuration>) -> Self {
        Self { config }
    }

${methods}
}

impl fmt::Debug for ${T} {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct(${q(T)}).finish_non_exhaustive()
    }
}
`;
  });
  writeFileSync(
    join(dir, 'groups.rs'),
    `// Code generated by scripts/render-meta.ts from the OpenAPI spec. DO NOT EDIT.
//
// One struct per API group, wrapping the generated functions. Each method has the generated function's
// parameters (after the configuration) and returns the crate's [\`Error\`].

use std::fmt;
use std::sync::Arc;

use crate::error::Error;
use crate::generated::apis::{self, configuration::Configuration};
use crate::generated::models;

${structs.join('\n')}`,
  );
}
