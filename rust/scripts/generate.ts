import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { renderMeta } from './render-meta.ts';

const pkg = resolve(import.meta.dirname, '..');
const root = resolve(pkg, '..');
const run = (cmd: string, args: string[], cwd = root) => execFileSync(cmd, args, { cwd, stdio: 'inherit' });

run('pnpm', ['exec', 'tsx', 'scripts/prepare-spec.ts', '--lang', 'rust']);

const out = resolve(pkg, 'build/out');
rmSync(out, { recursive: true, force: true });
run('pnpm', [
  'exec', 'openapi-generator-cli', 'generate',
  '-g', 'rust',
  '--library', 'reqwest',
  '-i', 'rust/build/openapi.json',
  '-o', 'rust/build/out',
  '--global-property', 'apiDocs=false,modelDocs=false,apiTests=false,modelTests=false',
  '--additional-properties=packageName=tiktok_shop_api_generated,supportMiddleware=true,supportAsync=true',
  // The spec has a schema called Option, which collides with std::option::Option.
  '--model-name-mappings=Option=OptionValue',
]);

// Only src/apis and src/models: the generator's Cargo.toml, README and git_push.sh are discarded.
const dest = resolve(pkg, 'src/generated');
rmSync(dest, { recursive: true, force: true });
mkdirSync(dest, { recursive: true });
cpSync(resolve(out, 'src/apis'), resolve(dest, 'apis'), { recursive: true });
cpSync(resolve(out, 'src/models'), resolve(dest, 'models'), { recursive: true });

// The generated code names its own modules `crate::apis` and `crate::models`; here they live under `crate::generated`.
function rewrite(dir: string): void {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) rewrite(p);
    else if (name.endsWith('.rs')) {
      const src = readFileSync(p, 'utf8');
      const fixed = src.replace(/\bcrate::(?!generated\b)/g, 'crate::generated::');
      if (fixed !== src) writeFileSync(p, fixed);
    }
  }
}
rewrite(dest);

// src/generated/mod.rs: the generator's own `pub mod` lines, plus the rendered files.
const lib = readFileSync(resolve(out, 'src/lib.rs'), 'utf8');
const mods = lib.split('\n').filter((l) => /^pub (mod|use) /.test(l));
const mod = `// Code generated by scripts/generate.ts from the OpenAPI spec. DO NOT EDIT.
#![allow(unused_imports, clippy::all)]

${mods.join('\n')}
pub mod groups;
pub mod meta;
`;
writeFileSync(resolve(dest, 'mod.rs'), mod);

renderMeta(resolve(pkg, 'build/meta.json'), dest);
if (!existsSync(resolve(dest, 'groups.rs'))) throw new Error('groups.rs was not rendered');
run('rustfmt', ['--edition', '2021', 'src/generated/meta.rs', 'src/generated/groups.rs'], pkg);
