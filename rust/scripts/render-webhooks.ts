import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

type Schema = {
  type?: string | string[];
  properties?: Record<string, Schema>;
  items?: Schema;
  allOf?: Schema[];
  anyOf?: Schema[];
  oneOf?: Schema[];
  $ref?: string;
};
interface Webhook {
  type: number;
  schema: string;
  eventType?: string;
}

/** Marks "every element of the array" in a path. */
export const EACH = '[]';

const kinds = (s: Schema): string[] => (Array.isArray(s.type) ? s.type : s.type ? [s.type] : []);

/**
 * Every path, from the root of `schema`, to a property whose value is a string. Arrays are walked
 * (`EACH`), objects by property name. serde refuses a JSON number for a `String` field, and TikTok sends
 * ids such as `shop_id` as numbers, so the parser turns the number at these paths into its text first.
 */
export function stringPaths(schemas: Record<string, Schema>, root: string): string[][] {
  const out: string[][] = [];
  const walk = (s: Schema, path: string[], stack: string[]): void => {
    if (s.$ref) {
      const name = s.$ref.replace('#/components/schemas/', '');
      if (stack.includes(name)) return;
      const target = schemas[name];
      if (!target) throw new Error(`unresolved $ref ${s.$ref}`);
      return walk(target, path, [...stack, name]);
    }
    for (const part of [...(s.allOf ?? []), ...(s.anyOf ?? []), ...(s.oneOf ?? [])]) walk(part, path, stack);
    const k = kinds(s);
    if (k.includes('string') && path.length) out.push(path);
    if (k.includes('array') && s.items) walk(s.items, [...path, EACH], stack);
    for (const [name, p] of Object.entries(s.properties ?? {})) walk(p, [...path, name], stack);
  };
  walk({ $ref: `#/components/schemas/${root}` }, [], []);
  const seen = new Set<string>();
  return out.filter((p) => {
    const key = JSON.stringify(p);
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

const q = (s: string) => JSON.stringify(s);

/** `OrderStatusChangeWebhook` to `OrderStatusChange`. */
export const variantName = (schema: string) => schema.replace(/Webhook$/, '') || schema;

/** Write `<dir>/webhooks.rs`: the `WebhookEvent` enum, `decode`, and the string-path table. */
export function renderWebhooks(specPath: string, metaPath: string, dir: string): void {
  const schemas = (JSON.parse(readFileSync(specPath, 'utf8')) as { components: { schemas: Record<string, Schema> } }).components.schemas;
  const webhooks = (JSON.parse(readFileSync(metaPath, 'utf8')) as { webhooks: Webhook[] }).webhooks.slice().sort((a, b) => a.type - b.type);

  // The generator PascalCases acronyms (SKUStatusChangeWebhook becomes SkuStatusChangeWebhook), so find each
  // model's struct by a case-insensitive match.
  const structs = new Map<string, string>();
  for (const f of readdirSync(join(dir, 'models')).filter((n) => n.endsWith('.rs'))) {
    for (const m of readFileSync(join(dir, 'models', f), 'utf8').matchAll(/^pub struct (\w+)/gm)) structs.set(m[1].toLowerCase(), m[1]);
  }

  const names = new Set<string>(['Unknown']);
  const variants = webhooks.map((w) => {
    const v = variantName(w.schema);
    if (names.has(v)) throw new Error(`webhook variant ${v} (${w.schema}) is not unique`);
    names.add(v);
    const model = structs.get(w.schema.toLowerCase());
    if (!model) throw new Error(`no generated model for webhook schema ${w.schema}`);
    return { ...w, variant: v, model, paths: stringPaths(schemas, w.schema) };
  });

  const enumRows = variants.map((v) => `    /// Webhook type ${v.type}${v.eventType ? ` (\`${v.eventType}\`)` : ''}.\n    ${v.variant}(Box<models::${v.model}>),`);
  const typeArms = variants.map((v) => `            WebhookEvent::${v.variant}(_) => ${v.type},`);
  const pathTables = variants.map((v) => {
    const rows = v.paths.map((p) => `    &[${p.map(q).join(', ')}],`).join('\n');
    return `const PATHS_${v.type}: &[&[&str]] = &[\n${rows}\n];`;
  });
  const pathArms = variants.map((v) => `        ${v.type} => PATHS_${v.type},`);
  const decodeArms = variants.map(
    (v) => `        ${v.type} => known(${v.type}, raw, WebhookEvent::${v.variant}),`,
  );

  writeFileSync(
    join(dir, 'webhooks.rs'),
    `// Code generated by scripts/render-webhooks.ts from the OpenAPI spec. DO NOT EDIT.
//
// One variant per webhook type in the spec, holding that type's generated model. \`decode\` is called by
// \`crate::webhooks\` with the integer \`type\`; no generated union is involved.

use serde_json::Value;

use crate::error::Error;
use crate::generated::models;
use crate::webhooks::known;

/// A parsed webhook: one variant per webhook type, holding that type's model, or [\`WebhookEvent::Unknown\`]
/// for a type this SDK does not know.
///
/// The enum is \`non_exhaustive\`: new webhook types arrive with new releases. Match with a \`_\` arm.
#[derive(Debug, Clone, PartialEq)]
#[non_exhaustive]
pub enum WebhookEvent {
${enumRows.join('\n')}
    /// A webhook whose integer \`type\` is not in the spec. \`raw\` is the whole body.
    Unknown { event_type: i64, raw: Value },
}

impl WebhookEvent {
    /// The integer \`type\` of the webhook.
    pub fn event_type(&self) -> i64 {
        match self {
${typeArms.join('\n')}
            WebhookEvent::Unknown { event_type, .. } => *event_type,
        }
    }
}

${pathTables.join('\n\n')}

/// The string-typed property paths of a webhook type's model (\`"[]"\` is every array element), or none.
pub fn string_paths(event_type: i64) -> &'static [&'static [&'static str]] {
    match event_type {
${pathArms.join('\n')}
        _ => &[],
    }
}

/// Builds the event for a webhook type from its body, which must be a JSON object.
pub(crate) fn decode(event_type: i64, raw: Value) -> Result<WebhookEvent, Error> {
    match event_type {
${decodeArms.join('\n')}
        _ => Ok(WebhookEvent::Unknown { event_type, raw }),
    }
}
`,
  );
}
