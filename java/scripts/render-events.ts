import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

interface Webhook {
  type: number;
  schema: string;
  eventType?: string;
}

const HEADER = '// Code generated by scripts/render-events.ts from the OpenAPI spec. DO NOT EDIT.\n\n';

/** "OrderStatusChangeWebhook" → "OrderStatusChange". */
const base = (schema: string) => schema.replace(/Webhook$/, '');

/**
 * Write `<generatedDir>/event/`: one `XxxEvent` class per webhook (extends the hand-written `WebhookEvent`,
 * wraps the generated `XxxWebhook` model), `WebhookEventVisitor` and `WebhookEvents` (the type → event dispatch).
 */
export function renderEvents(metaPath: string, generatedDir: string): void {
  const hooks = (JSON.parse(readFileSync(metaPath, 'utf8')) as { webhooks: Webhook[] }).webhooks;
  const dir = join(generatedDir, 'event');
  mkdirSync(dir, { recursive: true });
  const names = new Set<string>();
  for (const w of hooks) {
    if (!w.schema.endsWith('Webhook')) throw new Error(`webhook schema ${w.schema} does not end in "Webhook"`);
    const cls = `${base(w.schema)}Event`;
    if (names.has(cls)) throw new Error(`duplicate event class ${cls}`);
    names.add(cls);
    writeFileSync(
      join(dir, `${cls}.java`),
      `${HEADER}package com.isaackogan.tiktok.shop.generated.event;

import com.google.gson.JsonObject;
import com.isaackogan.tiktok.shop.WebhookEvent;
import com.isaackogan.tiktok.shop.generated.model.${w.schema};

/** A webhook of type ${w.type}${w.eventType ? ` (${w.eventType})` : ''}. */
public final class ${cls} extends WebhookEvent {
    /** The webhook's {@code type}. */
    public static final int TYPE = ${w.type};

    private final ${w.schema} payload;

    public ${cls}(${w.schema} payload, JsonObject raw) {
        super(TYPE, raw);
        this.payload = payload;
    }

    /** The parsed body. */
    public ${w.schema} getPayload() {
        return payload;
    }

    @Override
    public <R> R accept(WebhookEventVisitor<R> visitor) {
        return visitor.visit${base(w.schema)}(this);
    }
}
`,
    );
  }

  const visits = hooks.map(
    (w) => `    default R visit${base(w.schema)}(${base(w.schema)}Event event) {
        return visitOther(event);
    }
`,
  );
  writeFileSync(
    join(dir, 'WebhookEventVisitor.java'),
    `${HEADER}package com.isaackogan.tiktok.shop.generated.event;

import com.isaackogan.tiktok.shop.UnknownWebhookEvent;
import com.isaackogan.tiktok.shop.WebhookEvent;

/**
 * Override the events you care about; every other one, and the unknown event, falls through to {@link #visitOther}.
 *
 * @param <R> what {@link WebhookEvent#accept} returns
 */
public interface WebhookEventVisitor<R> {
    /** Where every event you did not override ends up. Returns null unless you override it. */
    default R visitOther(WebhookEvent event) {
        return null;
    }

    default R visitUnknown(UnknownWebhookEvent event) {
        return visitOther(event);
    }

${visits.join('\n')}}
`,
  );

  const cases = hooks.map(
    (w) => `            case ${w.type}:
                return new ${base(w.schema)}Event(JSON.getGson().fromJson(raw, ${w.schema}.class), raw);`,
  );
  writeFileSync(
    join(dir, 'WebhookEvents.java'),
    `${HEADER}package com.isaackogan.tiktok.shop.generated.event;

import com.google.gson.JsonObject;
import com.isaackogan.tiktok.shop.WebhookEvent;
import com.isaackogan.tiktok.shop.generated.JSON;
import com.isaackogan.tiktok.shop.generated.model.*;

/** Maps a webhook {@code type} to its event class. Use {@code Webhooks.parse}, which checks the body first. */
public final class WebhookEvents {
    private WebhookEvents() {}

    /** The event for {@code type}, or null when this SDK does not know the type. Throws on a body the model rejects. */
    public static WebhookEvent fromJson(int type, JsonObject raw) {
        switch (type) {
${cases.join('\n')}
            default:
                return null;
        }
    }
}
`,
  );
}
