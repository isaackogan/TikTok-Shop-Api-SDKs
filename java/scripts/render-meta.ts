import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

interface Operation {
  operationId: string;
  tag: string;
  group: string;
  method: string;
  path: string;
  requiresShopCipher: boolean;
}
interface Webhook {
  type: number;
  schema: string;
  eventType?: string;
}
interface Meta {
  operations: Operation[];
  webhooks: Webhook[];
}

/** Public instance methods of a generated `XxxApi` class, by class name. The `*Call`/`*WithHttpInfo`/`*Async` variants are skipped. */
export function findApis(apiDir: string): Map<string, Set<string>> {
  const apis = new Map<string, Set<string>>();
  for (const f of readdirSync(apiDir).filter((n) => n.endsWith('Api.java'))) {
    const src = readFileSync(join(apiDir, f), 'utf8');
    const methods = new Set<string>();
    for (const m of src.matchAll(/^    public (?!okhttp3\.Call|ApiResponse<)[\w<>\[\], .]+? (\w+)\(/gm)) methods.add(m[1]);
    apis.set(f.replace(/\.java$/, ''), methods);
  }
  return apis;
}

const q = (s: string) => JSON.stringify(s);

/** Write `<generatedDir>/Meta.java` from `meta.json` and the generated API classes. */
export function renderMeta(metaPath: string, generatedDir: string): void {
  const meta = JSON.parse(readFileSync(metaPath, 'utf8')) as Meta;
  const apis = findApis(join(generatedDir, 'api'));

  const groups = new Map<string, { tag: string; api: string }>();
  const rows: string[] = [];
  for (const op of meta.operations) {
    const hits = [...apis.entries()].filter(([, ms]) => ms.has(op.operationId));
    if (hits.length !== 1) {
      throw new Error(`operation ${op.operationId}: expected exactly one generated method, found ${hits.map(([n]) => n).join(', ') || 'none'}`);
    }
    const api = hits[0][0];
    const prev = groups.get(op.group);
    if (prev && prev.api !== api) throw new Error(`group ${op.group} spans ${prev.api} and ${api}`);
    groups.set(op.group, { tag: op.tag, api });
    rows.push(
      `            new Operation(${q(op.operationId)}, ${q(op.tag)}, ${q(op.group)}, ${q(api)}, ${q(op.method.toUpperCase())}, ${q(op.path)}, ${op.requiresShopCipher})`,
    );
  }
  const groupRows = [...groups.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([g, v]) => `            new Group(${q(g)}, ${q(v.tag)}, ${q(v.api)})`);
  const webhookRows = meta.webhooks.map(
    (w) => `            new Webhook(${w.type}, ${q(w.schema)}, ${w.eventType ? q(w.eventType) : 'null'})`,
  );
  const eventTypes = meta.webhooks
    .filter((w) => w.eventType)
    .sort((a, b) => a.type - b.type)
    .map((w) => `        m.put(${w.type}, ${q(w.eventType!)});`);

  const out = `// Code generated by scripts/render-meta.ts from the OpenAPI spec. DO NOT EDIT.

package com.isaackogan.tiktok.shop.generated;

import java.util.Arrays;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/** What the OpenAPI spec says about every operation, group and webhook. */
public final class Meta {
    private Meta() {}

    /** One API operation. */
    public static final class Operation {
        public final String operationId;
        public final String tag;
        /** The canonical camelCase group name, e.g. "fulfilledByTikTok". */
        public final String group;
        /** The simple name of the generated API class holding the method, e.g. "OrdersApi". */
        public final String apiClass;
        /** Upper case. */
        public final String method;
        public final String path;
        public final boolean requiresShopCipher;

        Operation(String operationId, String tag, String group, String apiClass, String method, String path, boolean requiresShopCipher) {
            this.operationId = operationId;
            this.tag = tag;
            this.group = group;
            this.apiClass = apiClass;
            this.method = method;
            this.path = path;
            this.requiresShopCipher = requiresShopCipher;
        }
    }

    /** One API group. */
    public static final class Group {
        public final String name;
        public final String tag;
        public final String apiClass;

        Group(String name, String tag, String apiClass) {
            this.name = name;
            this.tag = tag;
            this.apiClass = apiClass;
        }
    }

    /** One webhook type. */
    public static final class Webhook {
        public final int type;
        /** The simple name of the generated model, e.g. "OrderStatusChangeWebhook". */
        public final String schema;
        /** May be null. */
        public final String eventType;

        Webhook(int type, String schema, String eventType) {
            this.type = type;
            this.schema = schema;
            this.eventType = eventType;
        }
    }

    public static final List<Operation> OPERATIONS = Collections.unmodifiableList(Arrays.asList(
${rows.join(',\n')}));

    public static final List<Group> GROUPS = Collections.unmodifiableList(Arrays.asList(
${groupRows.join(',\n')}));

    public static final List<Webhook> WEBHOOKS = Collections.unmodifiableList(Arrays.asList(
${webhookRows.join(',\n')}));

    /** A webhook type to its event name. */
    public static final Map<Integer, String> EVENT_TYPES;

    static {
        Map<Integer, String> m = new LinkedHashMap<>();
${eventTypes.join('\n')}
        EVENT_TYPES = Collections.unmodifiableMap(m);
    }
}
`;
  writeFileSync(join(generatedDir, 'Meta.java'), out);
}
