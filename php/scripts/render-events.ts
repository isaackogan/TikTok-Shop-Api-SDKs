import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { webhookModels, type SchemaNode, type WebhookModel } from '../../scripts/lib/webhook-models.ts';

interface Webhook {
  type: number;
  schema: string;
  eventType?: string;
}

const NS = 'TikTokShop\\Api\\Generated';
/** A PHP single-quoted string literal. */
const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** The event class for a webhook schema: `OrderStatusChangeWebhook` becomes `OrderStatusChangeEvent`. */
export function eventClass(schema: string): string {
  if (!schema.endsWith('Webhook')) throw new Error(`webhook schema ${schema} does not end in "Webhook"`);
  return `${schema.slice(0, -'Webhook'.length)}Event`;
}

/**
 * Every model reachable from a webhook: its required property names, and which properties hold other such models
 * (directly, as a list, or as a string-keyed map). The generated PHP models do not throw for a missing property, so
 * the parser checks presence on the decoded JSON with this table. Built by the shared `webhookModels`, which throws at
 * generation on a property shape the check cannot follow (a list of lists, an inline object, a combinator other than a
 * nullable `$ref`).
 */
export function requiredModels(schemas: Record<string, SchemaNode>, webhooks: Webhook[]): Map<string, WebhookModel> {
  return new Map(Object.entries(webhookModels(schemas, webhooks)));
}

/**
 * Write, into `<dir>`:
 *  - `Event/<Name>Event.php`: one final class per webhook, extending `TikTokShop\Api\WebhookEvent`, with a typed `getPayload()`;
 *  - `WebhookEvents.php`: type => [event class, model class, schema], the required-property table, and the union as a type alias.
 */
export function renderEvents(metaPath: string, specPath: string, dir: string): void {
  const meta = JSON.parse(readFileSync(metaPath, 'utf8')) as { webhooks: Webhook[] };
  const spec = JSON.parse(readFileSync(specPath, 'utf8')) as { components: { schemas: Record<string, SchemaNode> } };
  const webhooks = [...meta.webhooks].sort((a, b) => a.type - b.type);
  const names = new Set<string>();
  for (const w of webhooks) {
    const c = eventClass(w.schema);
    if (names.has(c)) throw new Error(`two webhooks render to the event class ${c}`);
    names.add(c);
  }

  mkdirSync(join(dir, 'Event'), { recursive: true });
  for (const w of webhooks) {
    const cls = eventClass(w.schema);
    const what = w.eventType ? `\`${w.eventType}\` webhook` : 'webhook';
    writeFileSync(
      join(dir, 'Event', `${cls}.php`),
      `<?php
// Code generated by scripts/render-events.ts from the OpenAPI spec. DO NOT EDIT.

declare(strict_types=1);

namespace ${NS}\\Event;

use ${NS}\\Model\\${w.schema};
use TikTokShop\\Api\\WebhookEvent;

/** The ${what} (type ${w.type}). */
final class ${cls} extends WebhookEvent
{
    public const TYPE = ${w.type};

    /** @param array<string, mixed> $raw The decoded JSON body. */
    public function __construct(array $raw, private readonly ${w.schema} $payload)
    {
        parent::__construct(self::TYPE, $raw);
    }

    public function getPayload(): ${w.schema}
    {
        return $this->payload;
    }
}
`,
    );
  }

  const models = requiredModels(spec.components.schemas, webhooks);
  const modelRows = [...models.entries()]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([name, m]) => {
      const children = Object.entries(m.children).map(([p, [kind, model]]) => `${q(p)} => [${q(kind)}, ${q(model)}]`);
      return `        ${q(name)} => [[${m.required.map(q).join(', ')}], [${children.join(', ')}]],`;
    });
  const typeRows = webhooks.map(
    (w) => `        ${w.type} => [\\${NS}\\Event\\${eventClass(w.schema)}::class, \\${NS}\\Model\\${w.schema}::class, ${q(w.schema)}],`,
  );
  const union = [...webhooks.map((w) => `Event\\${eventClass(w.schema)}`), '\\TikTokShop\\Api\\UnknownWebhookEvent'];

  writeFileSync(
    join(dir, 'WebhookEvents.php'),
    `<?php
// Code generated by scripts/render-events.ts from the OpenAPI spec. DO NOT EDIT.

declare(strict_types=1);

namespace ${NS};

/**
 * The webhook events of the spec.
 *
 * @phpstan-type WebhookEventUnion ${union.join('|')}
 * @psalm-type WebhookEventUnion = ${union.join('|')}
 */
final class WebhookEvents
{
    /**
     * Webhook type => [event class, model class, schema name].
     *
     * @var array<int, array{class-string<\\TikTokShop\\Api\\WebhookEvent>, class-string, string}>
     */
    public const TYPES = [
${typeRows.join('\n')}
    ];

    /**
     * Schema name => [required property names, [property => [kind, schema]]], for every model a webhook can contain.
     * The kind is 'object', 'list' or 'map'. The generated models do not throw for a missing property, so the parser
     * checks presence on the decoded JSON.
     *
     * @var array<string, array{list<string>, array<string, array{string, string}>}>
     */
    public const REQUIRED = [
${modelRows.join('\n')}
    ];
}
`,
  );
}
