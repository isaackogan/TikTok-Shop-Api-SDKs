import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

interface Operation {
  operationId: string;
  tag: string;
  group: string;
  method: string;
  path: string;
  requiresShopCipher: boolean;
}
interface Webhook {
  type: number;
  schema: string;
  eventType?: string;
}
interface Meta {
  operations: Operation[];
  webhooks: Webhook[];
}

/** A PHP single-quoted string literal. */
const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const NS = 'TikTokShop\\Api\\Generated';

/**
 * Write `<dir>/Meta.php` from `meta.json` and the generated `Api/*Api.php` files.
 * Every operation must be found as `public function <operationId>(` in exactly one generated Api class.
 */
export function renderMeta(metaPath: string, dir: string): void {
  const meta = JSON.parse(readFileSync(metaPath, 'utf8')) as Meta;
  const owners = new Map<string, string[]>();
  for (const f of readdirSync(join(dir, 'Api')).filter((n) => n.endsWith('Api.php'))) {
    const cls = f.replace(/\.php$/, '');
    for (const m of readFileSync(join(dir, 'Api', f), 'utf8').matchAll(/^    public function (\w+)\(/gm)) {
      owners.set(m[1], [...(owners.get(m[1]) ?? []), cls]);
    }
  }

  const groups = new Map<string, { tag: string; cls: string }>();
  const rows: string[] = [];
  for (const op of meta.operations) {
    const hits = owners.get(op.operationId) ?? [];
    if (hits.length !== 1) {
      throw new Error(`operation ${op.operationId}: expected exactly one generated method, found ${hits.join(', ') || 'none'}`);
    }
    const g = groups.get(op.group) ?? { tag: op.tag, cls: hits[0] };
    if (g.cls !== hits[0]) throw new Error(`group ${op.group} spans ${g.cls} and ${hits[0]}`);
    groups.set(op.group, g);
    rows.push(
      `        [${q(op.operationId)}, ${q(op.group)}, ${q(op.method.toUpperCase())}, ${q(op.path)}, ${op.requiresShopCipher}],`,
    );
  }
  const groupRows = [...groups.entries()]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([name, v]) => `        ${q(name)} => [${q(v.tag)}, ${q(`${NS}\\Api\\${v.cls}`)}],`);
  const webhookRows = meta.webhooks.map(
    (w) => `        [${w.type}, ${q(w.schema)}, ${w.eventType ? q(w.eventType) : 'null'}],`,
  );
  const eventRows = meta.webhooks
    .filter((w) => w.eventType)
    .sort((a, b) => a.type - b.type)
    .map((w) => `        ${w.type} => ${q(w.eventType!)},`);

  writeFileSync(
    join(dir, 'Meta.php'),
    `<?php
// Code generated by scripts/render-meta.ts from the OpenAPI spec. DO NOT EDIT.

declare(strict_types=1);

namespace ${NS};

/** The API operations, groups and webhook types of the spec. */
final class Meta
{
    /**
     * Every API operation: [operationId (also the method name on the group), group, HTTP method (upper case),
     * path template, requiresShopCipher].
     *
     * @var list<array{string, string, string, string, bool}>
     */
    public const OPERATIONS = [
${rows.join('\n')}
    ];

    /**
     * Every API group: camelCase property name on the client => [tag, generated Api class].
     *
     * @var array<string, array{string, class-string}>
     */
    public const GROUPS = [
${groupRows.join('\n')}
    ];

    /**
     * Every webhook type: [type, schema name, event type or null].
     *
     * @var list<array{int, string, string|null}>
     */
    public const WEBHOOKS = [
${webhookRows.join('\n')}
    ];

    /**
     * Webhook type => event name.
     *
     * @var array<int, string>
     */
    public const EVENT_TYPES = [
${eventRows.join('\n')}
    ];
}
`,
  );
}
