import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

interface Operation {
  operationId: string;
  tag: string;
  group: string;
  method: string;
  path: string;
  requiresShopCipher: boolean;
}
interface Webhook {
  type: number;
  schema: string;
  eventType?: string;
}
interface Meta {
  operations: Operation[];
  webhooks: Webhook[];
}

/** A C# regular string literal. */
const q = (s: string) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

const NS = 'TikTokShop.Api.Generated';

/** `getOrderList` -> `GetOrderList`; the generator PascalCases operation ids the same way. */
const pascal = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

/**
 * Write `<dir>/Meta.cs` from `meta.json` and the generated `Api/*Api.cs` files.
 * Every operation must be found as a public `<OperationId>Async(` method in exactly one generated Api class.
 */
export function renderMeta(metaPath: string, dir: string): void {
  const meta = JSON.parse(readFileSync(metaPath, 'utf8')) as Meta;
  const owners = new Map<string, string[]>();
  for (const f of readdirSync(join(dir, 'Api')).filter((n) => /Api\.cs$/.test(n))) {
    const cls = f.replace(/\.cs$/, '');
    const text = readFileSync(join(dir, 'Api', f), 'utf8');
    for (const m of text.matchAll(/^\s+public (?:async )?[\w<>?.,\s]+? (\w+)Async\(/gm)) {
      owners.set(m[1], [...(owners.get(m[1]) ?? []), cls]);
    }
  }

  const groups = new Map<string, { tag: string; cls: string }>();
  const rows: string[] = [];
  for (const op of meta.operations) {
    const hits = [...new Set(owners.get(pascal(op.operationId)) ?? [])];
    if (hits.length !== 1) {
      throw new Error(`operation ${op.operationId}: expected exactly one generated method, found ${hits.join(', ') || 'none'}`);
    }
    const g = groups.get(op.group) ?? { tag: op.tag, cls: hits[0] };
    if (g.cls !== hits[0]) throw new Error(`group ${op.group} spans ${g.cls} and ${hits[0]}`);
    groups.set(op.group, g);
    rows.push(
      `        new(${q(pascal(op.operationId))}, ${q(pascal(op.group))}, ${q(op.method.toUpperCase())}, ${q(op.path)}, ${op.requiresShopCipher}),`,
    );
  }
  const groupRows = [...groups.entries()]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([name, v]) => `        new(${q(pascal(name))}, ${q(v.tag)}, typeof(Api.${v.cls})),`);
  const webhookRows = meta.webhooks.map(
    (w) => `        new(${w.type}, ${q(w.schema)}, ${w.eventType ? q(w.eventType) : 'null'}),`,
  );
  const eventRows = meta.webhooks
    .filter((w) => w.eventType)
    .sort((a, b) => a.type - b.type)
    .map((w) => `        [${w.type}] = ${q(w.eventType!)},`);

  writeFileSync(
    join(dir, 'Meta.cs'),
    `// <auto-generated>
// Code generated by scripts/render-meta.ts from the OpenAPI spec. DO NOT EDIT.
// </auto-generated>
#nullable enable
using System;
using System.Collections.Generic;

namespace ${NS};

/// <summary>One API operation: the generated method is <c>{OperationId}Async</c> on the group's Api class.</summary>
public sealed record OperationInfo(string OperationId, string Group, string HttpMethod, string Path, bool RequiresShopCipher);

/// <summary>One API group: its PascalCase property name on the client, its tag and its generated Api class.</summary>
public sealed record GroupInfo(string Name, string Tag, Type ApiType);

/// <summary>One webhook type.</summary>
public sealed record WebhookInfo(int Type, string Schema, string? EventType);

/// <summary>The API operations, groups and webhook types of the spec.</summary>
public static class Meta
{
    /// <summary>Every API operation.</summary>
    public static readonly IReadOnlyList<OperationInfo> Operations = new OperationInfo[]
    {
${rows.join('\n')}
    };

    /// <summary>Every API group.</summary>
    public static readonly IReadOnlyList<GroupInfo> Groups = new GroupInfo[]
    {
${groupRows.join('\n')}
    };

    /// <summary>Every webhook type.</summary>
    public static readonly IReadOnlyList<WebhookInfo> Webhooks = new WebhookInfo[]
    {
${webhookRows.join('\n')}
    };

    /// <summary>Webhook type to event name.</summary>
    public static readonly IReadOnlyDictionary<int, string> EventTypes = new Dictionary<int, string>
    {
${eventRows.join('\n')}
    };
}
`,
  );
}
