import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

interface Webhook {
  type: number;
  schema: string;
  eventType?: string;
}

const HEADER = '// Code generated by scripts/render-events.ts from the OpenAPI spec. DO NOT EDIT.\n\n';

/** "OrderStatusChangeWebhook" → "OrderStatusChange". */
const base = (schema: string) => schema.replace(/Webhook$/, '');

interface Prop {
  kotlin: string;
  json: string;
  required: boolean;
  type: string;
}

/** The constructor properties of every generated `data class`, by class name. */
export function readModels(modelsDir: string): Map<string, Prop[]> {
  const models = new Map<string, Prop[]>();
  for (const f of readdirSync(modelsDir).filter((n) => n.endsWith('.kt'))) {
    const src = readFileSync(join(modelsDir, f), 'utf8');
    const cls = /^data class (\w+) \(/m.exec(src);
    if (!cls) continue;
    // The constructor ends at the first line that closes the parameter list.
    const start = src.indexOf('\n', cls.index);
    const end = src.indexOf('\n)', start);
    const body = src.slice(start, end < 0 ? src.length : end);
    const props: Prop[] = [];
    for (const m of body.matchAll(/^ {4}@SerializedName\("([^"]+)"\)\n(?: {4}@[^\n]*\n)* {4}val (`?\w+`?): ([^\n]+)$/gm)) {
      const type = m[3].replace(/,$/, '').trim();
      const hasDefault = / = /.test(type);
      props.push({ kotlin: m[2].replace(/`/g, ''), json: m[1], required: !hasDefault && !type.endsWith('?'), type });
    }
    const declared = [...body.matchAll(/^ {4}val /gm)].length;
    if (declared !== props.length) throw new Error(`${f}: parsed ${props.length} of ${declared} properties`);
    models.set(cls[1], props);
  }
  return models;
}

const q = (s: string) => JSON.stringify(s).replace(/\$/g, '\\$');

/**
 * Write two files into `<generatedDir>`:
 *  - `WebhookEvent.kt`, package `com.isaackogan.tiktok.shop`: the sealed class `WebhookEvent`, one nested subclass per webhook
 *    and `Unknown`, plus the internal type → event dispatch. A sealed class's subclasses must share its package and module, so
 *    the base is rendered here too, and the file's directory does not match its package.
 *  - `WebhookRequired.kt`: for every model reachable from a webhook, its required non-null properties (gson leaves a missing
 *    one as null, which would break Kotlin's null-safety later).
 */
export function renderEvents(metaPath: string, generatedDir: string): void {
  const hooks = (JSON.parse(readFileSync(metaPath, 'utf8')) as { webhooks: Webhook[] }).webhooks;
  const models = readModels(join(generatedDir, 'models'));
  const names = new Set<string>(['Unknown']);
  const classes: string[] = [];
  const cases: string[] = [];
  for (const w of hooks) {
    if (!w.schema.endsWith('Webhook')) throw new Error(`webhook schema ${w.schema} does not end in "Webhook"`);
    if (!models.has(w.schema)) throw new Error(`webhook schema ${w.schema} has no generated model`);
    const cls = base(w.schema);
    if (names.has(cls)) throw new Error(`duplicate event class ${cls}`);
    names.add(cls);
    classes.push(`    /** A webhook of type ${w.type}${w.eventType ? ` (${w.eventType})` : ''}. */
    class ${cls}(
        /** The parsed body. */
        val payload: ${w.schema},
        raw: JsonObject,
    ) : WebhookEvent(TYPE, raw) {
        override fun toString(): String = "WebhookEvent.${cls}(payload=$payload)"

        companion object {
            /** The webhook's \`type\`. */
            const val TYPE: Int = ${w.type}
        }
    }
`);
    cases.push(`        ${w.type} -> WebhookEvent.${cls}(gson.fromJson(raw, ${w.schema}::class.java), raw)`);
  }
  writeFileSync(
    join(generatedDir, 'WebhookEvent.kt'),
    `${HEADER}package com.isaackogan.tiktok.shop

import com.google.gson.JsonObject
import com.isaackogan.tiktok.shop.generated.infrastructure.Serializer
${hooks.map((w) => `import com.isaackogan.tiktok.shop.generated.models.${w.schema}`).sort().join('\n')}

/**
 * A parsed webhook. Narrow it with \`when\`, which needs no \`else\` branch:
 *
 * \`\`\`
 * when (event) {
 *     is WebhookEvent.OrderStatusChange -> println(event.payload.data?.orderId)
 *     is WebhookEvent.Unknown -> println("a type this SDK does not know: \${event.type}")
 *     else -> {}
 * }
 * \`\`\`
 *
 * This class and its subclasses are rendered together because a sealed class's subclasses must share its package and module.
 * The package is \`com.isaackogan.tiktok.shop\`, even though the file lives in the generated folder.
 */
sealed class WebhookEvent(
    /** The webhook's integer \`type\`. */
    val type: Int,
    /** The body as received, parsed. */
    val raw: JsonObject,
) {
${classes.join('\n')}
    /** A webhook whose \`type\` this SDK does not know. [raw] holds the whole body. */
    class Unknown(type: Int, raw: JsonObject) : WebhookEvent(type, raw) {
        override fun toString(): String = "WebhookEvent.Unknown(type=$type)"
    }
}

/** The event for [type], or null when this SDK does not know the type. Throws on a body the model rejects. */
internal fun webhookEventOf(type: Int, raw: JsonObject): WebhookEvent? {
    val gson = Serializer.gson
    return when (type) {
${cases.join('\n')}
        else -> null
    }
}
`,
  );

  // Every model reachable from a webhook, with its required properties.
  const reach = new Map<string, Prop[]>();
  const visit = (name: string) => {
    if (reach.has(name)) return;
    const props = models.get(name);
    if (!props) return;
    reach.set(name, props);
    for (const p of props) for (const id of p.type.match(/\w+/g) ?? []) visit(id);
  };
  for (const w of hooks) visit(w.schema);
  const rows = [...reach.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([name, props]) => {
      const req = props.filter((p) => p.required).map((p) => `${q(p.kotlin)} to ${q(p.json)}`);
      return `        ${q(name)} to listOf(${req.join(', ')})`;
    });
  mkdirSync(generatedDir, { recursive: true });
  writeFileSync(
    join(generatedDir, 'WebhookRequired.kt'),
    `${HEADER}package com.isaackogan.tiktok.shop.generated

/**
 * Every model a webhook can contain, by simple class name, with its required non-null properties as (Kotlin name to JSON name).
 * gson leaves a missing one as null.
 */
internal object WebhookRequired {
    val MODELS: Map<String, List<Pair<String, String>>> = mapOf(
${rows.join(',\n')},
    )
}
`,
  );
}
