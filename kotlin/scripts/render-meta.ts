import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

interface Operation {
  operationId: string;
  tag: string;
  group: string;
  method: string;
  path: string;
  requiresShopCipher: boolean;
}
interface Webhook {
  type: number;
  schema: string;
  eventType?: string;
}
interface Meta {
  operations: Operation[];
  webhooks: Webhook[];
}

/** Member functions of each generated `XxxApi` class, by class name (the `*WithHttpInfo` / `*RequestConfig` variants are included; lookups are by exact operationId). */
export function findApis(apiDir: string): Map<string, Set<string>> {
  const apis = new Map<string, Set<string>>();
  for (const f of readdirSync(apiDir).filter((n) => n.endsWith('Api.kt'))) {
    const src = readFileSync(join(apiDir, f), 'utf8');
    const methods = new Set<string>();
    for (const m of src.matchAll(/^    fun (\w+)\(/gm)) methods.add(m[1]);
    apis.set(f.replace(/\.kt$/, ''), methods);
  }
  return apis;
}

const q = (s: string) => JSON.stringify(s).replace(/\$/g, '\\$');

/** Write `<generatedDir>/Meta.kt` from `meta.json` and the generated API classes. */
export function renderMeta(metaPath: string, generatedDir: string): void {
  const meta = JSON.parse(readFileSync(metaPath, 'utf8')) as Meta;
  const apis = findApis(join(generatedDir, 'apis'));

  const groups = new Map<string, { tag: string; api: string }>();
  const rows: string[] = [];
  for (const op of meta.operations) {
    const hits = [...apis.entries()].filter(([, ms]) => ms.has(op.operationId));
    if (hits.length !== 1) {
      throw new Error(`operation ${op.operationId}: expected exactly one generated method, found ${hits.map(([n]) => n).join(', ') || 'none'}`);
    }
    const api = hits[0][0];
    const prev = groups.get(op.group);
    if (prev && prev.api !== api) throw new Error(`group ${op.group} spans ${prev.api} and ${api}`);
    groups.set(op.group, { tag: op.tag, api });
    rows.push(
      `        Operation(${q(op.operationId)}, ${q(op.tag)}, ${q(op.group)}, ${q(api)}, ${q(op.method.toUpperCase())}, ${q(op.path)}, ${op.requiresShopCipher})`,
    );
  }
  const groupRows = [...groups.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([g, v]) => `        Group(${q(g)}, ${q(v.tag)}, ${q(v.api)})`);
  const webhookRows = meta.webhooks.map(
    (w) => `        Webhook(${w.type}, ${q(w.schema)}, ${w.eventType ? q(w.eventType) : 'null'})`,
  );
  const eventTypes = meta.webhooks
    .filter((w) => w.eventType)
    .sort((a, b) => a.type - b.type)
    .map((w) => `        ${w.type} to ${q(w.eventType!)}`);

  const out = `// Code generated by scripts/render-meta.ts from the OpenAPI spec. DO NOT EDIT.

package com.isaackogan.tiktok.shop.generated

/** What the OpenAPI spec says about every operation, group and webhook. */
object Meta {
    /** One API operation. */
    class Operation(
        val operationId: String,
        val tag: String,
        /** The canonical camelCase group name, e.g. "fulfilledByTikTok". */
        val group: String,
        /** The simple name of the generated API class holding the method, e.g. "OrdersApi". */
        val apiClass: String,
        /** Upper case. */
        val method: String,
        val path: String,
        val requiresShopCipher: Boolean,
    )

    /** One API group. */
    class Group(val name: String, val tag: String, val apiClass: String)

    /** One webhook type. */
    class Webhook(
        val type: Int,
        /** The simple name of the generated model, e.g. "OrderStatusChangeWebhook". */
        val schema: String,
        val eventType: String?,
    )

    val OPERATIONS: List<Operation> = listOf(
${rows.join(',\n')},
    )

    val GROUPS: List<Group> = listOf(
${groupRows.join(',\n')},
    )

    val WEBHOOKS: List<Webhook> = listOf(
${webhookRows.join(',\n')},
    )

    /** A webhook type to its event name. */
    val EVENT_TYPES: Map<Int, String> = linkedMapOf(
${eventTypes.join(',\n')},
    )
}
`;
  writeFileSync(join(generatedDir, 'Meta.kt'), out);
}
