// R13d fix-up for the generated Go API files: a 2xx body that does not decode into its model returns
// generated.DecodeError(...) (set by the tiktokshop package to build a *tiktokshop.Error) instead of a
// *GenericOpenAPIError.

const DECODE_CALL = '\terr = a.client.decode(&localVarReturnValue, localVarBody, localVarHTTPResponse.Header.Get("Content-Type"))\n';
const BLOCK =
  DECODE_CALL +
  '\tif err != nil {\n' +
  '\t\tnewErr := &GenericOpenAPIError{\n' +
  '\t\t\tbody:  localVarBody,\n' +
  '\t\t\terror: err.Error(),\n' +
  '\t\t}\n' +
  '\t\treturn localVarReturnValue, localVarHTTPResponse, newErr\n' +
  '\t}\n';
const FIXED =
  DECODE_CALL +
  '\tif err != nil {\n' +
  '\t\treturn localVarReturnValue, localVarHTTPResponse, DecodeError(localVarHTTPResponse, localVarBody, err)\n' +
  '\t}\n';

/** Replaces every post-decode error block of one api_*.go file. Throws unless every decode call is followed by it. */
export function fixDecodeErrors(src: string, file: string): string {
  const calls = src.split(DECODE_CALL).length - 1;
  const blocks = src.split(BLOCK).length - 1;
  if (calls === 0 || blocks !== calls) {
    throw new Error(`${file}: decode fix-up expected every one of ${calls} decode call(s) to be followed by the error block, found ${blocks}`);
  }
  return src.split(BLOCK).join(FIXED);
}

export const DECODE_ERROR_GO = `// Code generated by scripts/generate.ts. DO NOT EDIT.

package generated

import "net/http"

// DecodeError builds the error an operation returns when a 2xx body does not decode into its model. The
// tiktokshop package sets it, so that error is a *tiktokshop.Error with code -1, the HTTP status, the request ID
// and the decoder error as its cause (R13d). Do not set it yourself.
var DecodeError = func(resp *http.Response, body []byte, err error) error {
\treturn &GenericOpenAPIError{body: body, error: err.Error()}
}
`;
