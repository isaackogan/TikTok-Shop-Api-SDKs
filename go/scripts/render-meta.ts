import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { webhookModels, type SchemaNode } from '../../scripts/lib/webhook-models.ts';

interface Operation {
  operationId: string;
  tag: string;
  group: string;
  method: string;
  path: string;
  requiresShopCipher: boolean;
}
interface Webhook {
  type: number;
  schema: string;
  eventType?: string;
}
interface Meta {
  operations: Operation[];
  webhooks: Webhook[];
}

export interface Service {
  /** Generated service type, e.g. `OrdersAPIService`. */
  type: string;
  methods: string[];
}

/** Every `func (a *XService) Name(ctx context.Context[, pathParams]) ApiNameRequest` in the generated `api_*.go` files. */
export function findServices(sources: string[]): Map<string, Service> {
  const services = new Map<string, Service>();
  const re = /^func \(a \*(\w+)\) (\w+)\(ctx context\.Context(?:, [^)]*)?\) Api\w+Request \{/gm;
  for (const src of sources) {
    for (const m of src.matchAll(re)) {
      const s = services.get(m[1]) ?? { type: m[1], methods: [] };
      s.methods.push(m[2]);
      services.set(m[1], s);
    }
  }
  return services;
}

/** Field names of the generated `APIClient`, by service type: `OrdersAPI *OrdersAPIService`. */
export function findClientFields(clientGo: string): Map<string, string> {
  const fields = new Map<string, string>();
  for (const m of clientGo.matchAll(/^\t(\w+)\s+\*(\w+Service)$/gm)) fields.set(m[2], m[1]);
  return fields;
}

const q = (s: string) => JSON.stringify(s);

/** Write `<generatedDir>/meta.go` (package `generated`) from `meta.json` and the generated API files. */
export function renderMeta(metaPath: string, generatedDir: string, specPath: string): void {
  const meta = JSON.parse(readFileSync(metaPath, 'utf8')) as Meta;
  const sources = readdirSync(generatedDir)
    .filter((f) => /^api_.*\.go$/.test(f))
    .map((f) => readFileSync(join(generatedDir, f), 'utf8'));
  const services = findServices(sources);
  const fields = findClientFields(readFileSync(join(generatedDir, 'client.go'), 'utf8'));

  const rows: string[] = [];
  const groups = new Map<string, { tag: string; service: string; field: string }>();
  for (const op of meta.operations) {
    const hits = [...services.values()].filter((s) => s.methods.some((n) => n.toLowerCase() === op.operationId.toLowerCase()));
    if (hits.length !== 1) {
      throw new Error(`operation ${op.operationId}: expected exactly one generated method, found ${hits.map((h) => h.type).join(', ') || 'none'}`);
    }
    const [svc] = hits;
    const method = svc.methods.find((n) => n.toLowerCase() === op.operationId.toLowerCase())!;
    const field = fields.get(svc.type);
    if (!field) throw new Error(`service ${svc.type} is not a field of the generated APIClient`);
    const prev = groups.get(op.group);
    if (prev && prev.service !== svc.type) {
      throw new Error(`group ${op.group} spans services ${prev.service} and ${svc.type}`);
    }
    groups.set(op.group, { tag: op.tag, service: svc.type, field });
    rows.push(
      `\t{OperationID: ${q(op.operationId)}, Tag: ${q(op.tag)}, Group: ${q(op.group)}, Service: ${q(svc.type)}, Method: ${q(method)}, HTTPMethod: ${q(op.method.toUpperCase())}, Path: ${q(op.path)}, RequiresShopCipher: ${op.requiresShopCipher}},`,
    );
  }
  const groupRows = [...groups.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([g, v]) => `\t{Name: ${q(g)}, Tag: ${q(v.tag)}, Service: ${q(v.service)}, ClientField: ${q(v.field)}},`);
  const webhookRows = meta.webhooks.map(
    (w) => `\t{Type: ${w.type}, Schema: ${q(w.schema)}, EventType: ${q(w.eventType ?? '')}},`,
  );
  const eventTypes = meta.webhooks
    .filter((w) => w.eventType)
    .sort((a, b) => a.type - b.type)
    .map((w) => `\t${w.type}: ${q(w.eventType!)},`);

  const out = `// Code generated by scripts/render-meta.ts from the OpenAPI spec. DO NOT EDIT.

package generated

// OperationMeta describes one API operation.
type OperationMeta struct {
	OperationID string
	Tag         string
	// Group is the canonical camelCase group name, e.g. "fulfilledByTikTok".
	Group string
	// Service is the generated service type that holds Method, e.g. "OrdersAPIService".
	Service string
	// Method is the generated method name on Service, e.g. "GetOrderList".
	Method string
	// HTTPMethod is upper case.
	HTTPMethod          string
	Path                string
	RequiresShopCipher  bool
}

// GroupMeta describes one API group.
type GroupMeta struct {
	Name    string
	Tag     string
	Service string
	// ClientField is the field of APIClient holding the service.
	ClientField string
}

// WebhookMeta describes one webhook type.
type WebhookMeta struct {
	Type      int
	Schema    string
	EventType string
}

// Operations lists every API operation.
var Operations = []OperationMeta{
${rows.join('\n')}
}

// Groups lists every API group.
var Groups = []GroupMeta{
${groupRows.join('\n')}
}

// Webhooks lists every webhook type.
var Webhooks = []WebhookMeta{
${webhookRows.join('\n')}
}

// EventTypes maps a webhook type to its event name.
var EventTypes = map[int]string{
${eventTypes.join('\n')}
}
`;
  writeFileSync(join(generatedDir, 'meta.go'), out);

  renderWebhookModels(meta.webhooks, generatedDir);
  const spec = JSON.parse(readFileSync(specPath, 'utf8')) as { components?: { schemas?: Record<string, SchemaNode> } };
  writeFileSync(join(generatedDir, 'webhook_required.go'), renderWebhookRequired(spec.components?.schemas ?? {}, meta.webhooks));
}

/**
 * `webhook_required.go`: every model reachable from a webhook, with its required JSON properties and the properties
 * that hold other models. The generated models accept a JSON null for a required field (it decodes to the zero
 * value), so `Webhooks.Parse` checks the raw JSON against this table first (R28).
 */
export function renderWebhookRequired(schemas: Record<string, SchemaNode>, webhooks: Webhook[]): string {
  const models = webhookModels(schemas, webhooks);
  const rows = Object.entries(models).map(([name, m]) => {
    const children = Object.entries(m.children)
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([p, [kind, model]]) => `${q(p)}: {Kind: ${q(kind)}, Model: ${q(model)}}`);
    const req = m.required.map(q).join(', ');
    return `\t${q(name)}: {Required: []string{${req}}, Children: map[string]WebhookChild{${children.join(', ')}}},`;
  });
  return `// Code generated by scripts/render-meta.ts from the OpenAPI spec. DO NOT EDIT.

package generated

// WebhookChild is a property holding another model: directly (Kind "object"), as a list ("list"), or as a
// string-keyed map ("map").
type WebhookChild struct {
\tKind  string
\tModel string
}

// WebhookRequired lists one model's required JSON properties and the properties that hold other models.
type WebhookRequired struct {
\tRequired []string
\tChildren map[string]WebhookChild
}

// WebhookRequiredFields covers every model reachable from a webhook, by schema name.
var WebhookRequiredFields = map[string]WebhookRequired{
${rows.join('\n')}
}
`;
}

/**
 * Write `<generatedDir>/webhook_models.go`: a `WebhookType()` method on each generated webhook model, so the
 * models satisfy one interface without editing generated files, and the type -> model dispatch table.
 */
export function renderWebhookModels(webhooks: Webhook[], generatedDir: string): void {
  const sorted = [...webhooks].sort((a, b) => a.type - b.type);
  const methods = sorted
    .map(
      (w) => `// WebhookType returns ${w.type}, the webhook type this model carries.
func (*${w.schema}) WebhookType() int { return ${w.type} }
`,
    )
    .join('\n');
  const cases = sorted.map((w) => `	case ${w.type}:\n\t\treturn &${w.schema}{}`).join('\n');
  const out = `// Code generated by scripts/render-meta.ts from the OpenAPI spec. DO NOT EDIT.

package generated

// WebhookModel is implemented by every generated webhook model (a pointer to it). Type-switch on the
// concrete model to read its fields.
type WebhookModel interface {
	// WebhookType is the integer \`type\` of the webhook this model represents.
	WebhookType() int
}

// NewWebhookModel returns an empty model for a webhook type, or nil when the type is unknown.
func NewWebhookModel(webhookType int) WebhookModel {
	switch webhookType {
${cases}
	}
	return nil
}

${methods}`;
  writeFileSync(join(generatedDir, 'webhook_models.go'), out);
}
