"""Generate the Python SDK's `generated/` package.

1. `tsx scripts/prepare-spec.ts --lang python`  -> build/openapi.json, build/meta.json
2. openapi-python-client                        -> build/out/generated
3. copy build/out/generated                     -> src/tiktok_shop_api/generated
4. render generated/_meta.py and generated/_groups.py

Never edit the copied files by hand: change this script or the hand-written layer.
"""

from __future__ import annotations

import ast
import importlib
import json
import pprint
import re
import shutil
import subprocess
import sys
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent
ROOT = PKG.parent
OUT = PKG / "build" / "out"
DEST = PKG / "src" / "tiktok_shop_api" / "generated"
HEADER = "# Generated by scripts/generate.py from the OpenAPI spec. Do not edit.\n\n"


def run(cmd: list[str], cwd: Path) -> None:
    subprocess.run(cmd, cwd=cwd, check=True)


def camel_to_pascal(s: str) -> str:
    return s[:1].upper() + s[1:]


def camel_to_snake(s: str) -> str:
    # "TikTok" is one word (ruling R9): fulfilledByTikTok -> fulfilled_by_tiktok
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", s.replace("TikTok", "Tiktok")).lower()


def pyliteral(value: object) -> str:
    return pprint.pformat(value, width=100, sort_dicts=False)


def find_module(api_dir: Path, name: str) -> Path:
    hits = sorted(api_dir.glob(f"*/{name}.py"))
    if len(hits) != 1:
        raise SystemExit(f"operation module {name}.py: expected exactly one match, found {[str(h) for h in hits]}")
    return hits[0]


class OperationSource:
    """What the groups file needs to know about one generated operation module."""

    def __init__(self, path: Path):
        self.path = path
        tree = ast.parse(path.read_text(encoding="utf-8"))
        self.src = path.read_text(encoding="utf-8")
        self.imports: list[tuple[str, str]] = []  # (module, name) from `...models.x`
        self.needs_datetime = False
        self.type_names: set[str] = set()  # names from `...types` other than Response
        for node in tree.body:
            if isinstance(node, ast.ImportFrom) and node.level == 3 and (node.module or "").startswith("models."):
                for a in node.names:
                    self.imports.append((node.module, a.name))
            elif isinstance(node, ast.ImportFrom) and node.level == 3 and node.module == "types":
                self.type_names.update(a.name for a in node.names if a.name != "Response")
            elif isinstance(node, ast.Import) and any(a.name == "datetime" for a in node.names):
                self.needs_datetime = True
        fn = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "sync")
        self.doc = ast.get_docstring(fn) or ""
        self.returns = ast.get_source_segment(self.src, fn.returns) if fn.returns else "Any"
        a = fn.args
        if a.posonlyargs or a.vararg or a.kwarg:
            raise SystemExit(f"{path}: unsupported parameter kinds")
        # Path parameters are positional-or-keyword; everything else is keyword-only.
        pos_defaults = [None] * (len(a.args) - len(a.defaults)) + list(a.defaults)
        self.npos = len(a.args)
        self.params: list[tuple[str, str, str | None]] = []
        for arg, default in list(zip(a.args, pos_defaults)) + list(zip(a.kwonlyargs, a.kw_defaults)):
            if arg.arg == "client":
                continue
            ann = ast.get_source_segment(self.src, arg.annotation) if arg.annotation else "Any"
            dflt = ast.get_source_segment(self.src, default) if default is not None else None
            if dflt is not None and dflt != "UNSET":
                raise SystemExit(f"{path}: parameter {arg.arg} has an unsupported default {dflt!r}")
            self.params.append((arg.arg, ann, dflt))

    def render(self, *, is_async: bool, module: str, group_pkg: str) -> str:
        decl = [f"{n}: {ann}" + (f" = {d}" if d else "") for n, ann, d in self.params]
        kw = decl[self.npos :]
        sig = ["self"] + decl[: self.npos] + (["*"] + kw if kw else [])
        call = ", ".join(f"{n}={n}" for n, _, _ in self.params)
        doc = self.doc.split("\n\nRaises:")[0].rstrip().replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
        doc = re.sub(r"\n(?=[^\n])", "\n        ", doc)
        kind = "asyncio_detailed" if is_async else "sync_detailed"
        # Plain `def`/`async def` with a lazy import: importing the SDK must not import every operation module.
        head = "async def" if is_async else "def"
        aw = "await " if is_async else ""
        run = f"{aw}self._run(_op.{kind}" + (f", {call}" if call else "") + ")"
        return (
            f"    {head} {module}(\n        " + ",\n        ".join(sig) + f",\n    ) -> {self.returns}:\n"
            f'        """{doc}\n\n        Raises:\n            TikTokShopError: for a TikTok error code, a non-2xx status,\n'
            f'                an unparseable response, a network error or a timeout.\n        """\n'
            f"        from .api.{group_pkg} import {module} as _op\n\n"
            f"        return {run}\n"
        )


def main() -> None:
    run(["pnpm", "exec", "tsx", "scripts/prepare-spec.ts", "--lang", "python"], ROOT)
    shutil.rmtree(OUT, ignore_errors=True)
    exe = Path(sys.executable).with_name("openapi-python-client")
    run(
        [
            str(exe), "generate", "--path", "build/openapi.json", "--output-path", "build/out",
            "--overwrite", "--config", "generator-config.yaml",
        ],
        PKG,
    )
    shutil.rmtree(DEST, ignore_errors=True)
    shutil.copytree(OUT / "generated", DEST, ignore=shutil.ignore_patterns("__pycache__"))

    meta = json.loads((PKG / "build" / "meta.json").read_text(encoding="utf-8"))
    from openapi_python_client.strings import snake_case

    api_dir = DEST / "api"
    groups: dict[str, dict] = {}  # group -> {folder, tag, ops: [(method name, OperationSource)]}
    for op in meta["operations"]:
        name = snake_case(op["operationId"])
        mod = find_module(api_dir, name)
        g = groups.setdefault(op["group"], {"folder": mod.parent.name, "tag": op["tag"], "ops": []})
        if g["folder"] != mod.parent.name:
            raise SystemExit(f"group {op['group']} spans folders {g['folder']} and {mod.parent.name}")
        g["ops"].append((name, OperationSource(mod)))

    write_meta(meta)
    write_webhook_event(meta)
    write_groups(groups)


def write_meta(meta: dict) -> None:
    event_types = {w["type"]: w["eventType"] for w in meta["webhooks"] if w.get("eventType")}
    (DEST / "_meta.py").write_text(
        HEADER
        + "\nfrom __future__ import annotations\n\nfrom typing import Any\n\n"
        + f"OPERATIONS: list[dict[str, Any]] = {pyliteral(meta['operations'])}\n\n"
        + f"WEBHOOKS: list[dict[str, Any]] = {pyliteral(meta['webhooks'])}\n\n"
        + f"EVENT_TYPES: dict[int, str] = {pyliteral(event_types)}\n",
        encoding="utf-8",
    )


def write_webhook_event(meta: dict) -> None:
    names = sorted(w["schema"] for w in meta["webhooks"])
    (DEST / "_webhook_event.py").write_text(
        HEADER
        + "\nfrom __future__ import annotations\n\nfrom typing import TypeAlias\n\n"
        + "from .models import (\n" + "".join(f"    {n},\n" for n in names) + ")\n\n"
        + "#: Every generated webhook model, one per webhook type.\n"
        + "GeneratedWebhookEvent: TypeAlias = (\n    " + "\n    | ".join(names) + "\n)\n",
        encoding="utf-8",
    )


def write_groups(groups: dict[str, dict]) -> None:
    runtime_imports: set[tuple[str, str]] = set()
    needs_datetime = False
    type_names: set[str] = {"UNSET", "Unset"}
    for g in groups.values():
        for _, src in g["ops"]:
            type_names |= src.type_names
            runtime_imports.update(src.imports)
            needs_datetime |= src.needs_datetime
    seen: dict[str, str] = {}
    for mod, name in sorted(runtime_imports):
        if seen.setdefault(name, mod) != mod:
            raise SystemExit(f"model name {name} is imported from both {seen[name]} and {mod}")

    out = [HEADER, "from __future__ import annotations\n\n", "from typing import TYPE_CHECKING, Any\n\n"]
    out.append("from .._base import AsyncGroup, SyncGroup\n")
    out.append(f"from .types import {', '.join(sorted(type_names))}\n\n")
    out.append("if TYPE_CHECKING:\n")
    if needs_datetime:
        out.append("    import datetime\n\n")
    for mod, name in sorted(runtime_imports):
        out.append(f"    from .{mod} import {name}\n")
    out.append("\n\n")

    sync_map, async_map = [], []
    for group in sorted(groups):
        g = groups[group]
        pascal = camel_to_pascal(group)
        for is_async in (False, True):
            cls = ("Async" if is_async else "") + pascal + "Api"
            base = "AsyncGroup" if is_async else "SyncGroup"
            out.append(f"class {cls}({base}):\n    \"\"\"Operations tagged \\\"{g['tag']}\\\".\"\"\"\n\n")
            for name, src in sorted(g["ops"], key=lambda t: t[0]):
                out.append(src.render(is_async=is_async, module=name, group_pkg=g["folder"]))
                out.append("\n")
            out.append("\n")
            (async_map if is_async else sync_map).append((camel_to_snake(group), cls))
    for title, items in (("SYNC_GROUPS", sync_map), ("ASYNC_GROUPS", async_map)):
        out.append(f"{title}: dict[str, type] = {{\n")
        out.extend(f'    "{k}": {v},\n' for k, v in items)
        out.append("}\n\n")
    text = "".join(out).rstrip() + "\n"
    ast.parse(text)
    (DEST / "_groups.py").write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
